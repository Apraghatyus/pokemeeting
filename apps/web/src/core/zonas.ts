/** El nombre de una zona, o uno de reserva con su numero si no se conoce. */
export const nombreDeZona = (zona: number): string => {
  if (zona >= 0 && zona < NOMBRES_HOENN.length) return NOMBRES_HOENN[zona]!;
  // Rutas de Hoenn, 101 a 134.
  if (zona >= 0x10 && zona <= 0x31) return `Ruta ${101 + zona - 0x10}`;
  // Rutas de Kanto, 1 a 25.
  if (zona >= 0x65 && zona <= 0x7d) return `Ruta ${1 + zona - 0x65}`;
  return NOMBRES_SUELTOS[zona] ?? `Zona ${zona}`;
};

/**
 * Zonas que son la misma a efectos de captura.
 *
 * El juego parte algunas en dos -la segunda planta de una cueva, el Centro de
 * una ruta- y para "una captura por zona" son la misma. Se cuenta por la
 * primera.
 */
const MISMA_ZONA: Readonly<Record<number, number>> = {
  0x40: 0x3f,
  0x4b: 0x4a,
  0x4d: 0x4c,
  0x63: 0x68,
  0x64: 0x6e,
  0x82: 0x81,
  0xb3: 0xa7,
};

export const zonaCanonica = (zona: number): number => MISMA_ZONA[zona] ?? zona;

/** La region del mapa de un juego, por su codigo. */
export const regionDe = (codigoJuego: string | null | undefined): Region | null => {
  const juego = (codigoJuego ?? '').slice(0, 3).toUpperCase();
  if (juego === 'BPR' || juego === 'BPG') return 'kanto';
  if (juego === 'AXV' || juego === 'AXP' || juego === 'BPE') return 'hoenn';
  return null;
};

const ciudad = (zona: number, x: number, y: number): PuntoDelMapa => ({ zona, x, y, tipo: 'ciudad' });
const ruta = (zona: number, x: number, y: number): PuntoDelMapa => ({ zona, x, y, tipo: 'ruta' });
const lugar = (zona: number, x: number, y: number): PuntoDelMapa => ({ zona, x, y, tipo: 'lugar' });

/** Ruta N de Kanto. */
const k = (n: number) => 0x64 + n;
/** Ruta N de Hoenn. */
const h = (n: number) => 0x10 + n - 101;

