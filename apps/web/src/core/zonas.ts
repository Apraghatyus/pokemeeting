// Como se llama cada zona y donde se dibuja en el mapa.
//
// La zona es la "seccion de mapa" del juego: el numero que cada Pokemon lleva
// dentro como sitio de captura y el que dice donde esta el jugador. Es el mismo
// en los cinco juegos de tercera generacion: Hoenn va de 0x00 a 0x57, Kanto y
// las Islas Sete de 0x58 a 0xC4 (Esmeralda las conoce tambien, para los
// Pokemon que llegan de Rojo Fuego), y lo exclusivo de Esmeralda de 0xC5 en
// adelante. Sale de los proyectos de decompilacion (pokefirered, pokeemerald).
//
// LOS NOMBRES SON LOS DE LA VERSION EN ESPAÑOL hasta donde se sabe. Los de las
// ciudades y rutas son seguros; algunos sitios pequeños de las Islas Sete y de
// Hoenn pueden no coincidir letra a letra con el juego. Si alguno sale mal, se
// cambia aqui y ya.
//
// EL DIBUJO ES UN ESQUEMA, no el mapa del juego: cada zona es un punto en una
// cuadricula, colocado mas o menos donde esta, unido a sus vecinas. Sirve para
// ver de un vistazo que rutas quedan y donde anda cada uno, que es para lo que
// hace falta. Un mapa de verdad pediria las imagenes del juego.

